/** Stage or group label in the page language. Keeps any location after an underscore in English. */
export function groupName(locale: Locale, name: string | undefined | null): string {
  if (!name) return '';
  if (locale !== 'kn') return name;
  const text = name.trim();
  if (STAGE_KN[text]) return STAGE_KN[text];
  const m = text.match(/^group\s+([a-z0-9]+)(?:[_\s-]+(.+))?$/i);
  if (m) return `ಗುಂಪು ${m[1].toUpperCase()}${m[2] ? ` · ${m[2].trim()}` : ''}`;
  return text;
}

/** Season line from the league data ("Indian Super League, 2026-27"), with the competition name in the page language. */
export function seasonText(locale: Locale, competitionName: string, competitionNameKn: string, label: string): string {
  if (locale !== 'kn') return label;
  const season = label.match(/\d{4}-\d{2}/)?.[0];
  const name = label.startsWith(competitionName) ? competitionNameKn : label.replace(/,?\s*\d{4}-\d{2}$/, '');
  return season ? `${name}, ${digits(locale, season)}` : name;
}
